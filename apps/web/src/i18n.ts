let current: Locale = detectLocale();

function detectLocale(): Locale {
  try {
    const forced = new URLSearchParams(window.location.search).get("lang");
    const lang = (forced || navigator.language || "en").toLowerCase();
    return lang.startsWith("zh") ? "zh" : "en";
  } catch {
    return "en";
  }
}

export function setLocale(locale: string | undefined): void {
  if (!locale) return;
  current = locale.toLowerCase().startsWith("zh") ? "zh" : "en";
  document.documentElement.lang = current === "zh" ? "zh-CN" : "en";
}

export function getLocale(): Locale {
  return current;
}

/** Translate an English UI phrase. */
export function t(key: string): string {
  if (current === "zh") return ZH[key] ?? key;
  return key;
}
