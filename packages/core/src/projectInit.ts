/**
 * `/init` — scaffold shareable project guidance (AGENTS.md / CODEPILOT.md).
 * Analyzes the repo layout lightly and writes a commit-ready markdown file
 * the agent loads every session.
 */

import { access, readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

export interface InitProjectOptions {
  /** Prefer AGENTS.md (default) or CODEPILOT.md. */
  filename?: "AGENTS.md" | "CODEPILOT.md";
  /** Overwrite if the file already exists. */
  force?: boolean;
}

export interface InitProjectResult {
  path: string;
  created: boolean;
  /** True when file already existed and force was false. */
  skipped: boolean;
}

async function exists(path: string): Promise<boolean> {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

async function detectStackHints(cwd: string): Promise<string[]> {
  const hints: string[] = [];
  const names = await readdir(cwd).catch(() => [] as string[]);
  const set = new Set(names);
  if (set.has("package.json")) hints.push("Node / JavaScript or TypeScript (package.json)");
  if (set.has("pnpm-workspace.yaml") || set.has("pnpm-lock.yaml")) hints.push("pnpm workspace");
  if (set.has("Cargo.toml")) hints.push("Rust (Cargo)");
  if (set.has("go.mod")) hints.push("Go modules");
  if (set.has("pyproject.toml") || set.has("requirements.txt")) hints.push("Python");
  if (set.has("pom.xml") || set.has("build.gradle") || set.has("build.gradle.kts")) {
    hints.push("JVM (Maven/Gradle)");
  }
  if (set.has(".codepilot")) hints.push("CodePilot project config (.codepilot/)");
  return hints;
}

function scaffoldBody(cwdName: string, hints: string[]): string {
  const stack =
    hints.length > 0
      ? hints.map((h) => `- ${h}`).join("\n")
      : "- (edit) describe language, package manager, and main frameworks";
  return `# ${cwdName}

## Project

Briefly: what this repository does and who it is for.

## Stack

${stack}

## Build & test

\`\`\`bash
# (edit) install / build / test commands used in this repo
\`\`\`

## Conventions

- Prefer small, focused changes; match existing style.
- Do not commit or push unless the user asks.
- Put durable discoveries in memory (\`memory_write\`); keep this file for human-authored rules.

## Where things live

| Path | Purpose |
|------|---------|
| (edit) | |

## Review checklist

- [ ] Tests / typecheck for the touched area
- [ ] No secrets in the diff
- [ ] Docs or comments only when behaviour is non-obvious

---

_Generated by CodePilot \`/init\`. Edit freely and commit so every agent session inherits this guidance._
`;
}

/**
 * Create `AGENTS.md` (or `CODEPILOT.md`) in `cwd` if missing.
 */
export async function initProjectGuidance(
  cwd: string,
  opts: InitProjectOptions = {},
): Promise<InitProjectResult> {
  const filename = opts.filename ?? "AGENTS.md";
  const path = join(cwd, filename);
  if (await exists(path)) {
    if (!opts.force) {
      return { path, created: false, skipped: true };
    }
  }
  const base = cwd.replace(/[/\\]+$/, "").split(/[/\\]/).pop() || "project";
  const hints = await detectStackHints(cwd);
  await writeFile(path, scaffoldBody(base, hints), "utf-8");
  return { path, created: true, skipped: false };
}
