#!/usr/bin/env node
/**
 * Generate the web VFS module from the built web SPA (`apps/web/dist`). Each
 * file becomes a Bun `import … with { type: "file" }` so its bytes are embedded
 * in the compiled binary; the exported `webVfs` maps the SPA-relative path to
 * the embedded file path.
 *
 * Writes the COMPILED output `packages/protocol/dist/web-vfs.generated.js`,
 * overwriting the empty one `tsc` produced. This runs AFTER `tsc` (so the
 * committed source stays empty and type-checks without Bun's import-attribute
 * loader) and BEFORE the Bun compile step (which bundles from dist). In the
 * source / npm build the module stays empty, so filesystem lookup
 * (`detectWebRoot`) is used instead.
 */

import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { REPO_ROOT, log } from "./_util.mjs";

const webDist = join(REPO_ROOT, "apps", "web", "dist");
const outFile = join(REPO_ROOT, "packages", "protocol", "dist", "web-vfs.generated.js");

/** Recursively list every file under `dir`, returned as paths relative to it. */
function listFiles(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const abs = join(dir, name);
    if (statSync(abs).isDirectory()) {
      for (const child of listFiles(abs)) out.push(join(name, child));
    } else {
      out.push(name);
    }
  }
  return out;
}

function toPosix(p) {
  return p.split(sep).join("/");
}

function main() {
  let files;
  try {
    files = listFiles(webDist);
  } catch {
    throw new Error(`web dist not found at ${webDist} — build it first (pnpm --filter @codepilot/web build)`);
  }
  if (!files.includes("index.html")) {
    throw new Error(`web dist at ${webDist} has no index.html`);
  }

  const protocolDist = join(REPO_ROOT, "packages", "protocol", "dist");
  const imports = [];
  const entries = [];
  files.forEach((rel, i) => {
    const posix = toPosix(rel);
    const importPath = "./" + toPosix(relative(protocolDist, join(webDist, rel)));
    const ident = `f${i}`;
    imports.push(`import ${ident} from ${JSON.stringify(importPath)} with { type: "file" };`);
    entries.push(`  ${JSON.stringify(posix)}: ${ident},`);
  });

  const body = `// AUTO-GENERATED — do not edit by hand.
// Generated by scripts/package/gen-web-vfs.mjs from apps/web/dist. Each file is
// embedded in the Bun-compiled binary via \`with { type: "file" }\`.

${imports.join("\n")}

export const webVfs = {
${entries.join("\n")}
};
`;

  writeFileSync(outFile, body);
  log(`web VFS: ${files.length} files → ${outFile}`);
}

main();
